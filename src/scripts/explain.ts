import { writeFileSync } from 'node:fs';
import mongoose, { trusted } from 'mongoose';
import { connectDb, disconnectDb } from '../config/db.js';
import { env } from '../config/env.js';
import { rangeToWindow } from '../lib/dates.js';
import { Doctor } from '../modules/doctors/doctor.model.js';
import { doctorService } from '../modules/doctors/doctor.service.js';
import { Patient } from '../modules/patients/patient.model.js';
import { patientService } from '../modules/patients/patient.service.js';
import { toSort } from '../lib/pagination.js';

type Stage = { stage: string; inputStage?: Stage; inputStages?: Stage[]; indexName?: string };

const chain = (s: Stage | undefined): string[] =>
  !s
    ? []
    : [
        s.indexName ? `${s.stage}(${s.indexName})` : s.stage,
        ...chain(s.inputStage ?? s.inputStages?.[0]),
      ];

type Case = { title: string; query: string; run: () => Promise<unknown>; fullScanOk?: boolean };

async function main() {
  await connectDb();
  const [doctors, patients] = await Promise.all([
    Doctor.estimatedDocumentCount(),
    Patient.estimatedDocumentCount(),
  ]);
  const anyDoctor = (await Doctor.findOne().lean())!;

  const dFilter = doctorService.buildDoctorFilter;
  const pFilter = patientService.buildPatientFilter;
  const pDefaults = { dateField: 'visitDate' as const };
  const w = rangeToWindow('30d', env.APP_TIMEZONE);

  const cases: Case[] = [
    {
      title: '1. Doctors: prefix search `q="car"`, sort `-createdAt`, limit 10',
      query:
        'Doctor.find({ searchTokens: { $all: [/^car/] } }).sort({ createdAt: -1, _id: -1 }).limit(10)',
      run: () =>
        Doctor.find(dFilter({ q: 'car' }))
          .sort(toSort('-createdAt'))
          .limit(10)
          .explain('executionStats'),
    },
    {
      title: '2. Doctors: `specialization in [Cardiology]` + createdAt range',
      query:
        "Doctor.find({ specialization: { $in: ['Cardiology'] }, createdAt: { $gte, $lt } }).sort({ createdAt: -1, _id: -1 }).limit(10)",
      run: () =>
        Doctor.find(
          dFilter({ specialization: ['Cardiology'], from: '2025-06-01', to: '2026-12-31' }),
        )
          .sort(toSort('-createdAt'))
          .limit(10)
          .explain('executionStats'),
    },
    {
      title: '3. Patients: `condition in [critical]`, sort `-visitDate`, skip 100, limit 20',
      query:
        "Patient.find({ condition: { $in: ['critical'] } }).sort({ visitDate: -1, _id: -1 }).skip(100).limit(20)",
      run: () =>
        Patient.find(pFilter({ ...pDefaults, condition: ['critical'] }))
          .sort(toSort('-visitDate'))
          .skip(100)
          .limit(20)
          .explain('executionStats'),
    },
    {
      title: '4. Patients of one doctor, sort `-visitDate`',
      query: 'Patient.find({ doctor: <id> }).sort({ visitDate: -1, _id: -1 }).limit(10)',
      run: () =>
        Patient.find(pFilter({ ...pDefaults, doctorId: String(anyDoctor._id) }))
          .sort(toSort('-visitDate'))
          .limit(10)
          .explain('executionStats'),
    },
    {
      title: '5. Patients: prefix search `q="kar"`',
      query:
        'Patient.find({ searchTokens: { $all: [/^kar/] } }).sort({ visitDate: -1, _id: -1 }).limit(10)',
      run: () =>
        Patient.find(pFilter({ ...pDefaults, q: 'kar' }))
          .sort(toSort('-visitDate'))
          .limit(10)
          .explain('executionStats'),
    },
    {
      title: '6. Dashboard patients-over-time: `$match` on visitDate window (30d)',
      query:
        'Patient.aggregate([{ $match: { visitDate: { $gte, $lt } } }, { $group: { $dateTrunc … } }])',
      run: () =>
        Patient.aggregate([
          { $match: { visitDate: trusted({ $gte: w.start, $lt: w.end }) } },
          {
            $group: {
              _id: { $dateTrunc: { date: '$visitDate', unit: 'day', timezone: env.APP_TIMEZONE } },
              count: { $sum: 1 },
            },
          },
        ]).explain('executionStats'),
    },
    {
      fullScanOk: true,
      title: '7. Dashboard patients-per-doctor: `$group` by doctor (whole collection)',
      query:
        'Patient.aggregate([{ $group: { _id: "$doctor", count: { $sum: 1 } } }, { $sort }, { $limit: 10 }]).hint({ doctor: 1, visitDate: -1, _id: -1 })',
      run: () =>
        Patient.aggregate([
          { $group: { _id: '$doctor', count: { $sum: 1 } } },
          { $sort: { count: -1, _id: 1 } },
          { $limit: 10 },
        ]).explain('executionStats'),
    },
  ];

  let md = `# Query plans\n\nGenerated by \`npm run explain\` on ${new Date().toISOString()}.\n`;
  md += `Dataset: **${doctors.toLocaleString()} doctors, ${patients.toLocaleString()} patients** (MongoDB ${(await mongoose.connection.db!.admin().serverInfo()).version}).\n\n`;
  md += `| # | Query | Plan | keys examined | docs examined | returned | ms |\n|---|---|---|---|---|---|---|\n`;
  const details: string[] = [];
  let failed = false;

  for (const c of cases) {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const r = (await c.run()) as any;
    const stats = r.executionStats ?? r.stages?.[0]?.$cursor?.executionStats;
    const planRoot =
      r.queryPlanner?.winningPlan ?? r.stages?.[0]?.$cursor?.queryPlanner?.winningPlan;
    const plan = chain(planRoot?.queryPlan ?? planRoot);
    const text = plan.join(' → ');
    if (!c.fullScanOk && (!text.includes('IXSCAN') || text.includes('COLLSCAN'))) failed = true;
    md += `| ${c.title.split('.')[0]} | ${c.title.replace(/^\d+\.\s*/, '')} | \`${text}\` | ${stats?.totalKeysExamined} | ${stats?.totalDocsExamined} | ${stats?.nReturned} | ${stats?.executionTimeMillis} |\n`;
    details.push(`### ${c.title}\n\n\`\`\`js\n${c.query}\n\`\`\`\n\nWinning plan: \`${text}\`\n`);
    console.log(
      `${text.includes('COLLSCAN') && !c.fullScanOk ? '✗' : '✓'} ${c.title}\n   ${text} | keys=${stats?.totalKeysExamined} docs=${stats?.totalDocsExamined} returned=${stats?.nReturned} ${stats?.executionTimeMillis}ms`,
    );
  }

  md += `\n${details.join('\n')}\n`;
  md += `## Reading the table\n\n- \`IXSCAN\` = index range scan; \`FETCH\` = load documents for the keys the index returned; \`LIMIT\`/\`SKIP\` run after the index already delivered the sort order, so the indexed list queries (cases 2–4) have no in-memory \`SORT\` stage.\n- Prefix search stays index-backed because \`searchTokens\` holds normalised lowercase tokens and the query uses anchored, case-sensitive regexes (\`/^car/\`), which MongoDB turns into an index range scan. A \`/car/i\` or \`contains\` regex would be a full scan.\n- Cases 1 and 5 (prefix search) use the multikey \`searchTokens\` index to find matches, then sort only those matches in memory: a multikey regex range cannot also deliver sort order, but the in-memory sort never touches documents that did not match the search.\n- Case 6 is a covered index scan (\`PROJECTION_COVERED\`, 0 documents fetched).\n- Case 7 aggregates every patient by design (the "top doctors" chart). A hinted covered index scan was measured and was slower than the plain collection scan, so no hint is used; the result is cached for 60 s. Scale-up path: a denormalised \`patientCount\` on doctors kept with \`$inc\`.\n`;
  writeFileSync(new URL('../../docs/query-plans.md', import.meta.url), md);
  console.log('\nWrote docs/query-plans.md');
  await disconnectDb();
  if (failed) {
    console.error('WARNING: at least one plan has a COLLSCAN or in-memory SORT');
    process.exitCode = 1;
  }
}

main().catch(async (e) => {
  console.error(e);
  await disconnectDb().catch(() => 0);
  process.exit(1);
});
